def fill(tpl: str, params: dict) -> str:
    out = tpl
    for k, v in params.items():
        out = out.replace("{" + k + "}", str(v))
    return out


def gen_members(team: dict) -> list[dict]:
    members = []
    for i in range(N_MEMBERS):
        name, roman = make_person()
        role = team["lead_role"] if i == 0 else p(team["roles"])
        # 팀당 최소 3명은 최근 1시간 내 활동(온라인), 나머지는 최대 3주 분산
        active = rng.randint(2, 55) if (i < 3 or rng.random() < 0.2) else rng.randint(65, 30000)
        members.append({
            "agent_id": f"{team['space_id']}-{roman}",
            "name": name, "role": role, "owner": name,
            "last_active_min_ago": active,
            "activity": None,  # 문서/이슈 생성 후에 채운다
        })
    return members


def _project_of(team: dict, who: int, seq: int) -> str | None:
    """데모용 프로젝트 배정 — 팀이 `projects`를 정의한 경우만.

    실데이터에서 프로젝트는 a-mate가 세션의 git 저장소 이름을 실어 보낸 **사실**이고,
    마커가 붙기 시작한 2026-07-31 이후 발행분에만 있다. 그 성질을 데모에서도 지킨다:
    네 건에 한 건은 일부러 비워 **'분류 안 됨'이 있는 화면**을 만든다 — 전부 분류된
    화면은 실제로 존재하지 않는 상태이고, 정직성 규칙(스펙 §7)이 보여주려는 것도 그 구분이다.

    배정은 **사람 기준**이다: 각자 주 프로젝트가 있고 가끔 옆 프로젝트를 돕는다.
    문서 순번으로만 돌리면 전원이 모든 프로젝트에 걸려 이분 그래프가 뭉개진다 —
    프로젝트 축이 보여주려는 것은 '누가 어디에 모여 있나'이므로 쏠림이 있어야 읽힌다.
    겸업하는 사람이 프로젝트 사이를 잇는 선의 재료가 된다.

    rng를 쓰지 않는다 — 시드 스트림을 건드리면 다른 팀 파일까지 통째로 바뀐다."""
    projects = team.get("projects")
    if not projects:
        return None
    if seq % 4 == 3:
        return None  # 분류 안 됨 (마커 이전 발행분에 해당)
    shift = 1 if seq % 4 == 2 else 0  # 네 건 중 한 건은 옆 프로젝트를 돕는다
    return projects[(who + shift) % len(projects)]


def _unique_title(tpl: str, team: dict, seen: set) -> str:
    for _ in range(60):
        title = fill(tpl, team["params"]())
        if title not in seen:
            break
    else:
        base = f"{title} — {p(WEEKS)} 갱신"
        title, k = base, 2
        while title in seen:
            title = f"{base} ({k}차)"
            k += 1
    seen.add(title)
    return title


def gen_docs(team: dict, members: list[dict]) -> list[dict]:
    """멤버마다 3~6건씩 작성 — '각자 로컬 Claude로 일한 기록'이 멤버 전원에게 있게."""
    docs = []
    seen_titles: set[str] = set()
    other_teams = [t["space_id"] for t in TEAMS if t["space_id"] != team["space_id"]]
    idx = 0
    for who, author in enumerate(members):
        for seq in range(rng.randint(*DOCS_PER_MEMBER)):
            tpl = team["docs"][idx % len(team["docs"])]
            params = team["params"]()
            title = _unique_title(tpl[0], team, seen_titles)
            # 재사용 수는 롱테일: 절반 이상 0, 일부만 다회 재사용
            r = rng.random()
            reuse = 0 if r < 0.55 else (rng.randint(1, 3) if r < 0.9 else rng.randint(4, 15))
            cited = rng.sample(other_teams, k=min(len(other_teams), max(0, min(reuse, 3)))) if reuse else []
            body = "## 배경\n{}\n\n## 내용\n{}\n\n_이 문서는 {}의 로컬 Claude 세션(a-mate)에서 수집·정리되었습니다._".format(
                fill(tpl[1], params),
                "\n".join(f"- {fill(b, params)}" for b in tpl[2]),
                author["name"],
            )
            # 최근 3일 30%, 나머지는 최대 ~4개월 분산
            created = rng.randint(60, 4320) if rng.random() < 0.3 else rng.randint(4321, 172800)
            proj = _project_of(team, who, seq)
            docs.append({
                "doc_id": f"{team['space_id']}-doc-{idx + 1:04d}",
                "title": title,
                # 프로젝트를 모르는 문서는 키 자체를 넣지 않는다 — `null`을 적어두면
                # 프로젝트 축을 안 쓰는 팀 파일까지 전부 흔들려 diff가 읽히지 않는다.
                **({"project": proj} if proj else {}),
                "author": author["name"],
                "visibility": "org" if rng.random() < 0.6 else "space",
                "reuse_count": reuse,
                "cited_by": cited,
                "created_min_ago": created,
                "summary": fill(tpl[1], params),
                "body": body,
            })
            idx += 1
    return docs


def gen_issues(team: dict, members: list[dict]) -> list[dict]:
    """멤버마다 2~4건씩 등록 — 지식과 합쳐 멤버당 데이터 5개 이상."""
    issues = []
    seen_titles: set[str] = set()
    idx = 0
    for who, opener in enumerate(members):
        for seq in range(rng.randint(*ISSUES_PER_MEMBER)):
            tpl = team["issues"][idx % len(team["issues"])]
            title = _unique_title(tpl, team, seen_titles)
            r = rng.random()
            status = "resolved" if r < 0.45 else ("open" if r < 0.75 else "knowledge_linked")
            # 해결된 이슈는 과거에, 열린 이슈는 최근에 몰리게
            updated = rng.randint(1440, 129600) if status == "resolved" else rng.randint(10, 20160)
            proj = _project_of(team, who, seq)
            issues.append({
                "issue_id": f"{team['space_id']}-issue-{idx + 1:04d}",
                "title": title,
                **({"project": proj} if proj else {}),
                "status": status,
                "opened_by": opener["agent_id"],
                "updated_min_ago": updated,
            })
            idx += 1
    return issues


def gen_reuse_events(team: dict, docs: list[dict]) -> list[dict]:
    events = []
    # 재사용 많은 순 상위만 — 하이라이트(최다 재사용 지식)가 피드에 반드시 포함되게.
    cands = sorted((d for d in docs if d["cited_by"]), key=lambda d: -d["reuse_count"])[:MAX_REUSE_EVENTS]
    for d in cands:
        consumer = d["cited_by"][0]
        events.append({
            "doc_id": d["doc_id"],
            "source_space": team["space_id"],
            "consumer_space": consumer,
            "min_ago": rng.randint(30, 43200),
            "summary": f"{team['name']}의 『{d['title']}』 지식이 {TEAM_NAME[consumer]}에서 재사용되었습니다",
        })
    return events


def main() -> None:
    for team in TEAMS:
        members = gen_members(team)
        docs = gen_docs(team, members)
        issues = gen_issues(team, members)

        # 멤버의 최근 활동: 본인이 작성한 문서/이슈에서 배정 (말풍선·상세 패널 재료)
        docs_by_author: dict[str, list[dict]] = {}
        for d in docs:
            docs_by_author.setdefault(d["author"], []).append(d)
        issues_by_opener: dict[str, list[dict]] = {}
        for it in issues:
            issues_by_opener.setdefault(it["opened_by"], []).append(it)
        for m in members:
            mine_docs = docs_by_author.get(m["name"], [])
            mine_issues = issues_by_opener.get(m["agent_id"], [])
            if mine_docs and (not mine_issues or rng.random() < 0.6):
                m["activity"] = {"kind": "knowledge", "title": p(mine_docs)["title"]}
            elif mine_issues:
                m["activity"] = {"kind": "issue", "title": p(mine_issues)["title"]}

        # 칠판 하이라이트는 여기서 만들지 않는다 — 소스별 규칙이 갈리면 같은 칠판이 데이터
        # 출처에 따라 다르게 뜬다. 아래 events/reuse_events 풀만 제공하고 선정은 alens.pipeline이
        # 랭킹으로 한 곳에서 한다. 스펙: docs/archive/design/a-lens/specs/2026-07-30-room-board-highlight.md §6
        lo1, hi1, lo2, hi2 = team["visits"]
        payload = {
            "space": {"space_id": team["space_id"], "name": team["name"]},
            "visits": {"today": rng.randint(lo1, hi1), "total": rng.randint(lo2, hi2)},
            "members": members,
            "issues": issues,
            "knowledge": docs,
            "reuse_events": gen_reuse_events(team, docs),
        }
        out = OUT / team["file"]
        out.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"{out.name}: members={len(members)} issues={len(issues)} docs={len(docs)} reuse={len(payload['reuse_events'])}")


if __name__ == "__main__":
    main()
